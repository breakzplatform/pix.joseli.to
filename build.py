"""Render site/index.html from template.html.

Builds the static Pix BR Code ("copia e cola") payload, checks its CRC16,
and inlines a QR code as SVG so the page needs no JavaScript to show it.
"""

import base64
import hashlib
import html
import io
import re
from pathlib import Path

import segno

KEY = "apoie@pix.joseli.to"
MERCHANT_NAME = "Joselito"
MERCHANT_CITY = "Recife"

ROOT = Path(__file__).parent
TEMPLATE = ROOT / "template.html"
OUTPUT = ROOT / "site" / "index.html"
OG_QR = ROOT / "scripts" / "og-qr.svg"
# Pix symbol + logotype, monochrome (fill="currentColor"), traced from the
# vector artwork in the Banco Central "Manual de Uso da Marca Pix" v1.6, p. 6.
PIX_LOGO = ROOT / "scripts" / "pix-logo.svg"


def field(tag: str, value: str) -> str:
    if len(value) > 99:
        raise ValueError(f"EMV field {tag} longer than 99 characters")
    return f"{tag}{len(value):02d}{value}"


def crc16(data: str) -> str:
    """CRC-16/CCITT-FALSE (poly 0x1021, init 0xFFFF), as the BCB manual requires."""
    crc = 0xFFFF
    for byte in data.encode("utf-8"):
        crc ^= byte << 8
        for _ in range(8):
            crc = ((crc << 1) ^ 0x1021) if crc & 0x8000 else crc << 1
            crc &= 0xFFFF
    return f"{crc:04X}"


def pix_payload(key: str, name: str, city: str) -> str:
    account = field("00", "br.gov.bcb.pix") + field("01", key)
    body = (
        field("00", "01")
        + field("26", account)
        + field("52", "0000")
        + field("53", "986")
        + field("58", "BR")
        + field("59", name[:25])
        + field("60", city[:15])
        + field("62", field("05", "***"))
        + "6304"
    )
    return body + crc16(body)


def has_valid_crc(payload: str) -> bool:
    return payload[-4:] == crc16(payload[:-4])


def qr_svg(payload: str) -> str:
    buffer = io.BytesIO()
    segno.make(payload, error="m", micro=False).save(
        buffer,
        kind="svg",
        xmldecl=False,
        svgns=True,
        svgclass="qr",
        lineclass=None,
        omitsize=True,
        dark="#000",
        border=0,
        title="QR Code Pix",
    )
    return buffer.getvalue().decode("utf-8").strip()


def og_qr_svg(payload: str) -> str:
    """The same QR for the link preview: white paper and a 4-module quiet zone
    baked in, so it scans straight off the og.png thumbnail."""
    buffer = io.BytesIO()
    segno.make(payload, error="m", micro=False).save(
        buffer, kind="svg", xmldecl=False, svgns=True, omitsize=True,
        dark="#000", light="#fff", border=4,
    )
    return buffer.getvalue().decode("utf-8").strip()


def inline_logo() -> str:
    svg = PIX_LOGO.read_text(encoding="utf-8").strip()
    return svg.replace("<svg ", '<svg class="pix-logo" role="img" aria-label="Pix" ', 1)


def script_hashes(document: str) -> str:
    """CSP source list pinning every inline <script> by hash.

    Two are expected: the theme boot in <head>, which must run before first
    paint, and the page script at the end of <body>.
    """
    scripts = re.findall(r"<script>(.*?)</script>", document, flags=re.DOTALL)
    if len(scripts) != 2:
        raise SystemExit(f"expected two inline <script> blocks for the CSP, found {len(scripts)}")
    hashes = []
    for script in scripts:
        digest = hashlib.sha256(script.encode("utf-8")).digest()
        hashes.append("'sha256-" + base64.b64encode(digest).decode("ascii") + "'")
    return " ".join(hashes)


def self_test() -> None:
    # A payload generated by Nubank for the same key, with its own CRC.
    reference = (
        "00020126410014BR.GOV.BCB.PIX0119apoie@pix.joseli.to5204000053039865802BR"
        "5925Joselito Francisco do Nas6009SAO PAULO61080540900062210517ApoioNUsDGAX4oWX2"
        "630425C7"
    )
    assert has_valid_crc(reference), "CRC16 implementation disagrees with Nubank"
    assert crc16("123456789") == "29B1", "CRC-16/CCITT-FALSE check value"


def main() -> None:
    self_test()
    payload = pix_payload(KEY, MERCHANT_NAME, MERCHANT_CITY)
    assert has_valid_crc(payload)
    rendered = TEMPLATE.read_text(encoding="utf-8")
    replacements = {
        "{{KEY}}": html.escape(KEY),
        "{{PAYLOAD}}": html.escape(payload),
        "{{QR_SVG}}": qr_svg(payload),
        "{{PIX_LOGO}}": inline_logo(),
    }
    for placeholder, value in replacements.items():
        rendered = rendered.replace(placeholder, value)
    rendered = rendered.replace("{{SCRIPT_HASHES}}", script_hashes(rendered))
    leftover = re.findall(r"\{\{[A-Z_]+\}\}", rendered)
    if leftover:
        raise SystemExit(f"unreplaced placeholders: {leftover}")
    OUTPUT.parent.mkdir(exist_ok=True)
    OUTPUT.write_text(rendered, encoding="utf-8")
    OG_QR.parent.mkdir(exist_ok=True)
    OG_QR.write_text(og_qr_svg(payload) + "\n", encoding="utf-8")
    print(payload)


if __name__ == "__main__":
    main()
